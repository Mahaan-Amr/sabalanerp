assert(html.includes('size:A4 portrait'));
assert(html.includes('سفارش قطعی خرید'));
assert(html.includes('روز کاری'));
assert(html.includes('۲۶۲٬۹۳۷٬۵۰۰'));
assert(html.includes('&lt;script&gt;')&&!html.includes('<script>'));
