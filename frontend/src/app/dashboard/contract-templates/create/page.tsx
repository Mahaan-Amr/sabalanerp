'use client';
import { ErpBadge, ErpButton, ErpCard, ErpCheckbox, ErpField as SalesAuthoringField, ErpIconButton, ErpInlineState, ErpInput, ErpPressable, ErpSegmentedControl, ErpSelect, ErpTextarea } from '@/components/erp';
import { useState } from 'react';
import { useRouter } from 'next/navigation';
import Link from 'next/link';
import {
  FaArrowRight,
  FaSave,
  FaEye,
  FaFileContract,
  FaPlus,
  FaTrash,
  FaCode,
  FaTable,
  FaCalculator
} from 'react-icons/fa';
import { contractTemplatesAPI } from '@/lib/api';
import { SalesAuthoringPage, SalesAuthoringSection, hasContractTemplateDraft } from '@/features/sales/authoring/SalesAuthoringUi';

interface TemplateVariable {
  key: string;
  type: 'text' | 'number' | 'date' | 'array';
  label: string;
  required: boolean;
  autoGenerated?: boolean;
  calculated?: boolean;
  fields?: Record<string, TemplateVariable>;
}

interface TemplateStructure {
  sections: string[];
  tableConfig: {
    maxRows: number;
    columns: Array<{
      key: string;
      label: string;
      type: string;
      required?: boolean;
      autoIncrement?: boolean;
      calculated?: boolean;
    }>;
  };
}

interface TemplateCalculations {
  formulas: Record<string, string>;
  persianNumberConversion: boolean;
}

export default function CreateContractTemplatePage() {
  const router = useRouter();
  const [loading, setLoading] = useState(false);
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [activeTab, setActiveTab] = useState<'basic' | 'content' | 'variables' | 'structure' | 'calculations'>('basic');

  const [formData, setFormData] = useState({
    name: '',
    namePersian: '',
    description: '',
    category: 'sales',
    content: '',
    variables: {} as Record<string, TemplateVariable>,
    structure: {} as TemplateStructure,
    calculations: {} as TemplateCalculations
  });

  const [newVariable, setNewVariable] = useState({
    key: '',
    type: 'text' as const,
    label: '',
    required: false,
    autoGenerated: false,
    calculated: false
  });

  const categories = [
    { value: 'sales', label: 'فروش' },
    { value: 'service', label: 'خدمات' },
    { value: 'maintenance', label: 'نگهداری' },
    { value: 'general', label: 'عمومی' }
  ];

  const variableTypes = [
    { value: 'text', label: 'متن' },
    { value: 'number', label: 'عدد' },
    { value: 'date', label: 'تاریخ' },
    { value: 'array', label: 'آرایه' }
  ];

  const validateForm = () => {
    const newErrors: Record<string, string> = {};

    if (!formData.name.trim()) {
      newErrors.name = 'نام قالب الزامی است';
    }
    if (!formData.namePersian.trim()) {
      newErrors.namePersian = 'نام فارسی قالب الزامی است';
    }
    if (!formData.content.trim()) {
      newErrors.content = 'محتوای قالب الزامی است';
    }

    setErrors(newErrors);
    return Object.keys(newErrors).length === 0;
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!validateForm()) {
      return;
    }

    setLoading(true);
    try {
      const response = await contractTemplatesAPI.create({
        name: formData.name,
        namePersian: formData.namePersian,
        description: formData.description || undefined,
        category: formData.category,
        content: formData.content,
        variables: Object.keys(formData.variables).length > 0 ? formData.variables : undefined,
        structure: Object.keys(formData.structure).length > 0 ? formData.structure : undefined,
        calculations: Object.keys(formData.calculations).length > 0 ? formData.calculations : undefined
      });

      if (response.data.success) {
        router.push('/dashboard/contract-templates');
      } else {
        setErrors({ general: response.data.error || 'خطا در ایجاد قالب' });
      }
    } catch (error: any) {
      console.error('Create template error:', error);
      setErrors({ general: error.response?.data?.error || 'خطا در ارتباط با سرور' });
    } finally {
      setLoading(false);
    }
  };

  const addVariable = () => {
    if (!newVariable.key || !newVariable.label) {
      setErrors({ variable: 'کلید و برچسب متغیر الزامی است' });
      return;
    }

    if (formData.variables[newVariable.key]) {
      setErrors({ variable: 'متغیر با این کلید قبلا وجود دارد' });
      return;
    }

    setFormData({
      ...formData,
      variables: {
        ...formData.variables,
        [newVariable.key]: { ...newVariable }
      }
    });

    setNewVariable({
      key: '',
      type: 'text',
      label: '',
      required: false,
      autoGenerated: false,
      calculated: false
    });
    setErrors({});
  };

  const removeVariable = (key: string) => {
    const newVariables = { ...formData.variables };
    delete newVariables[key];
    setFormData({ ...formData, variables: newVariables });
  };

  const updateStructure = (field: keyof TemplateStructure, value: any) => {
    setFormData({
      ...formData,
      structure: {
        ...formData.structure,
        [field]: value
      }
    });
  };

  const updateCalculations = (field: keyof TemplateCalculations, value: any) => {
    setFormData({
      ...formData,
      calculations: {
        ...formData.calculations,
        [field]: value
      }
    });
  };

  const tabs = [
    { id: 'basic', label: 'اطلاعات پایه', icon: FaFileContract },
    { id: 'content', label: 'محتوای قالب', icon: FaCode },
    { id: 'variables', label: 'متغیرها', icon: FaTable },
    { id: 'structure', label: 'ساختار', icon: FaTable },
    { id: 'calculations', label: 'محاسبات', icon: FaCalculator }
  ];

  return (
    <SalesAuthoringPage
      title="ایجاد قالب قرارداد جدید"
      description="قالب جدید برای قراردادهای فروش"
      backHref="/dashboard/contract-templates"
      feedback={errors.general
        ? { kind: 'error', title: errors.general }
        : hasContractTemplateDraft(formData)
          ? { kind: 'stale', title: 'تغییرات قالب تا ثبت نهایی ذخیره نمی‌شوند.' }
          : undefined}
      progress={{ current: tabs.findIndex((tab) => tab.id === activeTab) + 1, total: tabs.length, label: tabs.find((tab) => tab.id === activeTab)?.label || '' }}
    >

      <form onSubmit={handleSubmit} className="space-y-6">
        {/* Tab Navigation */}
        <ErpSegmentedControl
          value={activeTab}
          onChange={setActiveTab}
          options={tabs.map((tab) => ({ value: tab.id as typeof activeTab, label: tab.label, icon: tab.icon }))}
        />

        {/* Basic Information Tab */}
        {activeTab === 'basic' && (
          <SalesAuthoringSection title="اطلاعات پایه" className="space-y-6">

            <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
              <SalesAuthoringField label="نام قالب (انگلیسی)" error={errors.name} required>
                <ErpInput
                  type="text"
                  value={formData.name}
                  onChange={(e) => setFormData({ ...formData, name: e.target.value })}
                  placeholder="Sales Contract Template"
                />
              </SalesAuthoringField>

              <SalesAuthoringField label="نام قالب (فارسی)" error={errors.namePersian} required>
                <ErpInput
                  type="text"
                  value={formData.namePersian}
                  onChange={(e) => setFormData({ ...formData, namePersian: e.target.value })}
                  placeholder="قالب قرارداد فروش"
                />
              </SalesAuthoringField>

              <SalesAuthoringField label="دسته‌بندی">
                <ErpSelect
                  value={formData.category}
                  onChange={(e) => setFormData({ ...formData, category: e.target.value })}
                  className="w-full"
                >
                  {categories.map(cat => (
                    <option key={cat.value} value={cat.value}>{cat.label}</option>
                  ))}
                </ErpSelect>
              </SalesAuthoringField>

              <SalesAuthoringField label="توضیحات" className="md:col-span-2">
                <ErpTextarea
                  value={formData.description}
                  onChange={(e) => setFormData({ ...formData, description: e.target.value })}
                  className="w-full h-24"
                  placeholder="توضیحات کوتاه درباره قالب..."
                />
              </SalesAuthoringField>
            </div>
          </SalesAuthoringSection>
        )}

        {/* Content Tab */}
        {activeTab === 'content' && (
          <SalesAuthoringSection title="محتوای قالب" className="space-y-6">

            <SalesAuthoringField label="محتوای HTML قالب" error={errors.content} required>
              <ErpTextarea
                value={formData.content}
                onChange={(e) => setFormData({ ...formData, content: e.target.value })}
                className="w-full h-96 font-mono text-sm"
                placeholder="محتوای HTML قالب با متغیرهای {{variableName}}..."
              />
            </SalesAuthoringField>

            <ErpCard className="p-4">
              <h3 className="text-[var(--sds-text-primary)] font-medium mb-2">راهنمای متغیرها:</h3>
              <ul className="sds-text-secondary space-y-1 text-sm">
                <li>• از {'{{variableName}}'} برای متغیرها استفاده کنید</li>
                <li>• از {'{{tableRows}}'} برای ردیف‌های جدول استفاده کنید</li>
                <li>• از CSS inline برای استایل‌دهی استفاده کنید</li>
                <li>• جهت RTL و فونت فارسی را در نظر بگیرید</li>
              </ul>
            </ErpCard>
          </SalesAuthoringSection>
        )}

        {/* Variables Tab */}
        {activeTab === 'variables' && (
          <SalesAuthoringSection title="متغیرهای قالب" className="space-y-6">

            {/* Add New Variable */}
            <SalesAuthoringSection title="افزودن متغیر جدید">
              <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-4">
                <SalesAuthoringField label="کلید متغیر" error={errors.variable && (!newVariable.key.trim() || !!formData.variables[newVariable.key]) ? errors.variable : undefined}>
                  <ErpInput
                    type="text"
                    value={newVariable.key}
                    onChange={(e) => setNewVariable({ ...newVariable, key: e.target.value })}
                    className="w-full"
                    placeholder="buyerName"
                  />
                </SalesAuthoringField>
                <SalesAuthoringField label="برچسب" error={errors.variable && !newVariable.label.trim() ? errors.variable : undefined}>
                  <ErpInput
                    type="text"
                    value={newVariable.label}
                    onChange={(e) => setNewVariable({ ...newVariable, label: e.target.value })}
                    className="w-full"
                    placeholder="نام خریدار"
                  />
                </SalesAuthoringField>
                <SalesAuthoringField label="نوع">
                <ErpSelect
                    value={newVariable.type}
                    onChange={(e) => setNewVariable({ ...newVariable, type: e.target.value as any })}
                    className="w-full"
                  >
                    {variableTypes.map(type => (
                      <option key={type.value} value={type.value}>{type.label}</option>
                    ))}
                  </ErpSelect>
              </SalesAuthoringField>
                <div className="flex items-end">
                  <ErpPressable
                    type="button"
                    onClick={addVariable}
                    tone="primary"
                    variant="solid"
                    className="px-4 py-2 w-full flex items-center justify-center gap-2"
                  >
                    <FaPlus className="h-4 w-4" />
                    <span>افزودن</span>
                  </ErpPressable>
                </div>
              </div>

              <div className="flex items-center gap-4 mt-4">
                <ErpCheckbox label="الزامی"
                    checked={newVariable.required}
                    onChange={(e) => setNewVariable({ ...newVariable, required: e.target.checked })}
                  />
                <ErpCheckbox label="تولید خودکار"
                    checked={newVariable.autoGenerated}
                    onChange={(e) => setNewVariable({ ...newVariable, autoGenerated: e.target.checked })}
                  />
                <ErpCheckbox label="محاسبه‌شده"
                    checked={newVariable.calculated}
                    onChange={(e) => setNewVariable({ ...newVariable, calculated: e.target.checked })}
                  />
              </div>

            </SalesAuthoringSection>

            {/* Existing Variables */}
            <div>
              <h3 className="text-[var(--sds-text-primary)] font-medium mb-4">متغیرهای موجود</h3>
              {Object.keys(formData.variables).length === 0 ? (
                <ErpInlineState kind="empty" title="هنوز متغیری اضافه نشده است" />
              ) : (
                <div className="space-y-2">
                  {Object.entries(formData.variables).map(([key, variable]) => (
                    <ErpCard key={key} className="flex items-center justify-between p-3">
                      <div className="flex items-center gap-4">
                        <div>
                          <span className="text-[var(--sds-text-primary)] font-medium">{variable.label}</span>
                          <span className="text-[var(--sds-text-muted)] text-sm mr-2">({key})</span>
                        </div>
                        <span className="text-[var(--sds-text-secondary)] text-sm">{variableTypes.find(t => t.value === variable.type)?.label}</span>
                        {variable.required && <ErpBadge tone="danger">الزامی</ErpBadge>}
                        {variable.autoGenerated && <ErpBadge tone="info">خودکار</ErpBadge>}
                        {variable.calculated && <ErpBadge tone="success">محاسبه‌شده</ErpBadge>}
                      </div>
                      <ErpIconButton
                        label={`حذف متغیر ${variable.label}`}
                        icon={FaTrash}
                        onClick={() => removeVariable(key)}
                        tone="danger"
                      />
                    </ErpCard>
                  ))}
                </div>
              )}
            </div>
          </SalesAuthoringSection>
        )}

        {/* Structure Tab */}
        {activeTab === 'structure' && (
          <SalesAuthoringSection title="ساختار قالب" className="space-y-6">

            <fieldset>
              <legend className="sds-text-primary mb-2 font-medium">بخش‌های قالب</legend>
              <div className="flex flex-wrap gap-2">
                {['header', 'table', 'footer'].map(section => (
                  <ErpCheckbox key={section} label={section === 'header' ? 'سربرگ' : section === 'table' ? 'جدول' : 'پابرگ'}
                      checked={formData.structure.sections?.includes(section) || false}
                      onChange={(e) => {
                        const sections = formData.structure.sections || [];
                        if (e.target.checked) {
                          updateStructure('sections', [...sections, section]);
                        } else {
                          updateStructure('sections', sections.filter(s => s !== section));
                        }
                      }}
                    />
                ))}
              </div>
            </fieldset>

            <SalesAuthoringField label="حداکثر ردیف جدول">
                <ErpInput
                type="number"
                value={formData.structure.tableConfig?.maxRows || 9}
                onChange={(e) => updateStructure('tableConfig', {
                  ...formData.structure.tableConfig,
                  maxRows: parseInt(e.target.value)
                })}
                className="w-32"
                min="1"
                max="20"
              />
              </SalesAuthoringField>
          </SalesAuthoringSection>
        )}

        {/* Calculations Tab */}
        {activeTab === 'calculations' && (
          <SalesAuthoringSection title="فرمول‌های محاسباتی" className="space-y-6">

            <fieldset>
              <legend className="sds-text-primary mb-2 font-medium">فرمول‌های محاسباتی</legend>
              <div className="space-y-4">
                <SalesAuthoringField label="محاسبه متر مربع">
                <ErpInput
                    type="text"
                    value={formData.calculations.formulas?.squareMeter || ''}
                    onChange={(e) => updateCalculations('formulas', {
                      ...formData.calculations.formulas,
                      squareMeter: e.target.value
                    })}
                    className="w-full"
                    placeholder="length * width"
                  />
              </SalesAuthoringField>
                <SalesAuthoringField label="محاسبه قیمت کل">
                <ErpInput
                    type="text"
                    value={formData.calculations.formulas?.totalPrice || ''}
                    onChange={(e) => updateCalculations('formulas', {
                      ...formData.calculations.formulas,
                      totalPrice: e.target.value
                    })}
                    className="w-full"
                    placeholder="squareMeter * unitPrice"
                  />
              </SalesAuthoringField>
                <SalesAuthoringField label="محاسبه مجموع کل">
                <ErpInput
                    type="text"
                    value={formData.calculations.formulas?.totalAmount || ''}
                    onChange={(e) => updateCalculations('formulas', {
                      ...formData.calculations.formulas,
                      totalAmount: e.target.value
                    })}
                    className="w-full"
                    placeholder="SUM(totalPrice)"
                  />
              </SalesAuthoringField>
              </div>
            </fieldset>

            <div>
              <ErpCheckbox label="تبدیل اعداد به فارسی"
                  checked={formData.calculations.persianNumberConversion || false}
                  onChange={(e) => updateCalculations('persianNumberConversion', e.target.checked)}
                />
            </div>
          </SalesAuthoringSection>
        )}

        {/* Submit Button */}
        <div className="flex items-center justify-end gap-4">
          <ErpButton label="انصراف" href="/dashboard/contract-templates" variant="ghost" tone="neutral" />
          <ErpPressable
            type="submit"
            disabled={loading}
            tone="primary"
            variant="solid"
            className="px-8 py-3 flex items-center gap-2 disabled:opacity-50"
          >
            {loading ? (
              <>
                <div className="animate-spin rounded-full h-4 w-4 border-b-2 border-[var(--sds-border-default)]"></div>
                <span>در حال ایجاد...</span>
              </>
            ) : (
              <>
                <FaSave className="h-5 w-5" />
                <span>ایجاد قالب</span>
              </>
            )}
          </ErpPressable>
        </div>
      </form>
    </SalesAuthoringPage>
  );
}
