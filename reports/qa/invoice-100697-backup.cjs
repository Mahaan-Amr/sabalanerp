// Keep recovery material outside the repository. Never print the encryption key.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawn } = require('node:child_process');
const { pipeline } = require('node:stream/promises');
const { Transform, Writable } = require('node:stream');
const folder = 'C:/Users/mahan/.codex/backups/invoice-100697-20261013';
const sshArgs = ['-o', 'BatchMode=yes', '-o', 'ConnectTimeout=12', '-i', 'C:/Users/mahan/.ssh/sabalan_codex_deploy_ed25519', 'root@94.182.85.254'];
const ssh = command => spawn('ssh', [...sshArgs, command], { windowsHide: true, stdio: ['pipe', 'pipe', 'pipe'] });
const done = child => new Promise((resolve, reject) => {
  let error = '';
  child.stderr.on('data', chunk => { error += chunk.toString(); });
  child.on('error', reject);
  child.on('close', code => code === 0 ? resolve() : reject(Error('SSH_OPERATION_FAILED_' + code + ': ' + error.slice(0, 400))));
});
const hashStream = hash => new Transform({ transform(chunk, encoding, callback) { hash.update(chunk); callback(null, chunk); } });
(async () => {
  const keyPath = path.join(folder, 'recovery-key.bin');
  const key = fs.existsSync(keyPath) ? fs.readFileSync(keyPath) : crypto.randomBytes(32), iv = crypto.randomBytes(12);
  if (!fs.existsSync(keyPath)) fs.writeFileSync(keyPath, key, { flag: 'wx', mode: 0o600 });
  const archive = path.join(folder, 'production-before-invoice-removal-' + Date.now() + '.dump.aesgcm');
  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  const plainHash = crypto.createHash('sha256');
  const child = ssh(`docker exec sabalanerp-postgres-1 sh -c 'pg_dump -U "$POSTGRES_USER" -d "$POSTGRES_DB" -Fc -Z6'`);
  const completion = done(child);
  child.stdin.end();
  await Promise.all([pipeline(child.stdout, hashStream(plainHash), cipher, fs.createWriteStream(archive, { flags: 'wx', mode: 0o600 })), completion]);
  const metadata = { contractNumber: '100697', capturedAt: new Date().toISOString(), format: 'PostgreSQL custom archive encrypted with AES-256-GCM', iv: iv.toString('hex'), authTag: cipher.getAuthTag().toString('hex'), plaintextSha256: plainHash.digest('hex'), bytes: fs.statSync(archive).size };
  const encryptedHash = crypto.createHash('sha256');
  for await (const chunk of fs.createReadStream(archive)) encryptedHash.update(chunk);
  metadata.ciphertextSha256 = encryptedHash.digest('hex');
  metadata.localArchive = archive;
  const manifestPath = path.join(folder, 'backup-manifest-' + Date.now() + '.json');
  fs.writeFileSync(manifestPath, JSON.stringify(metadata, null, 2), { flag: 'wx', mode: 0o600 });
  const fullDecipher = crypto.createDecipheriv('aes-256-gcm', key, iv);
  fullDecipher.setAuthTag(Buffer.from(metadata.authTag, 'hex'));
  const fullHash = crypto.createHash('sha256');
  await pipeline(fs.createReadStream(archive), fullDecipher, new Writable({ write(chunk, encoding, callback) { fullHash.update(chunk); callback(); } }));
  if (fullHash.digest('hex') !== metadata.plaintextSha256) throw Error('DECRYPT_HASH_MISMATCH');
  metadata.decryptVerified = true;
  const restore = ssh(`docker exec -i sabalanerp-postgres-1 sh -c 'umask 077; cat > /tmp/invoice-100697-backup-verify-20261013.dump; pg_restore --list /tmp/invoice-100697-backup-verify-20261013.dump; r=$?; rm -f /tmp/invoice-100697-backup-verify-20261013.dump; exit $r'`);
  const restoreDone = done(restore);
  let toc = '';
  restore.stdout.on('data', chunk => { toc += chunk.toString(); });
  const decipher = crypto.createDecipheriv('aes-256-gcm', key, iv);
  decipher.setAuthTag(Buffer.from(metadata.authTag, 'hex'));
  await Promise.all([pipeline(fs.createReadStream(archive), decipher, restore.stdin), restoreDone]);
  if (!toc.includes('accounting_financial_records') || !toc.includes('partner_case_revisions')) throw Error('ARCHIVE_VERIFICATION_FAILED');
  metadata.restoreListVerified = true;
  metadata.restoreListEntries = toc.split('\n').filter(line => /^\d+;/.test(line)).length;
  fs.writeFileSync(manifestPath, JSON.stringify(metadata, null, 2), { mode: 0o600 });
  fs.writeFileSync(path.join(folder, 'verified-backup-manifest.json'), JSON.stringify(metadata, null, 2), { mode: 0o600 });
  console.log(JSON.stringify({ ...metadata, localArchive: archive, keyLocation: keyPath }));
})().catch(error => { console.error(error.message); process.exitCode = 1; });
